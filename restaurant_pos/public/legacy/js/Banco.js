function cargarDatosBanco(idBanco1) {
    idBanco=idBanco1;
    var url = '../../../CONTROLADORES/bancoController.php';var nombre = $('#inputNombreA');var estado = $('#inputEstadoA'); $('#loading').css('display', 'block'); $.ajax({
        url: url,
        type: 'POST',
        typedata: 'json',
        data: {proceso: 'cargarDatos', id: idBanco},
        success: function (res) {
            var json = $.parseJSON(res);
            if (verificarError(json.error)) {
            return;
          }
           if (json.result != '') {nombre.val(json.result[0].nombre);estado.val(json.result[0].estado);
                $("#ModalBancoEdit").modal("show");
            }
                 else {
                alertify.error("ERROR INTENTE NUEVAMENTE");   }
                 $("#loading").css("display", "none");
                  }
    }).fail(function(xhr, ajaxOptions, thrownError){
    failErrors(xhr, ajaxOptions, thrownError);  
});
}function paginadorBanco() {
    $('#tableBanco').DataTable({
        'pagingType': 'full_numbers',
        'scrollY': '330px',
        'scrollCollapse': true,
        'paging': false,
        retrieve: true

    });
}function listarBanco(){

   $('#tableBanco').DataTable().destroy();
$('#tbodyBanco').empty();
  
    $.ajax({
        url: '../../../CONTROLADORES/bancoController.php',
        type: 'POST',
        typeData: 'json',
        data: {proceso: 'listarBanco'},
        success: function (res) {
            var json = $.parseJSON(res);
          if (verificarError(json.error)) {
            return;
          }
            for (var i = 0; i < json.result.length; i++) {
            $('#tbodyBanco').append('<tr>'+
                     '<td>'+json.result[i].nombre+
                     '<td>'+json.result[i].estado+'<td><button onclick="cargarDatosBanco('+json.result[i].id+')" class="btn btn-info"><i class="fa fa-pencil-square-o" aria-hidden="true"></i></button><button onclick="eliminarBanco('+json.result[i].id+')" class="btn btn-danger"><i class="fa fa-trash-o" aria-hidden="true"></i></button></tr>');
}
paginadorBanco();
            $('#loading').css('display', 'none');

        }
    }).fail(function(xhr, ajaxOptions, thrownError){
    failErrors(xhr, ajaxOptions, thrownError);  
});
}